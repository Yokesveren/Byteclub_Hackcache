"""
Writes the app's translation table from i18n/strings.py and checks it against the code. Run from app/:

    python i18n/build_strings.py

Reports English text used through tr()/trNow()/I18n.t() that has no Hindi or Urdu yet, and translations whose
{placeholders} do not match the English.
"""
import os, re, sys, glob

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from strings import S  # noqa: E402

SRC = os.path.join(HERE, "..", "androidApp", "src", "main", "java", "app", "sevasetu", "patient")
OUT = os.path.join(SRC, "ui", "i18n", "Strings.kt")

LIT = r'"((?:[^"\\]|\\.)*)"'
CALLS = [re.compile(r'\b(?:tr|trNow)\(\s*' + LIT), re.compile(r'I18n\.t\(\s*lang\s*,\s*' + LIT),
         re.compile(r'\bt\(\s*(?:if \([^)]*\) )?' + LIT), re.compile(r'\belse\s+' + LIT + r'\)')]


def unescape(s):
    return s.replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def kotlin(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("$", "\\$") + '"'


used = set()
for f in glob.glob(os.path.join(SRC, "**", "*.kt"), recursive=True):
    if f.endswith("Strings.kt"):
        continue
    text = open(f, encoding="utf8").read()
    for rx in CALLS:
        for m in rx.finditer(text):
            k = unescape(m.group(1))
            if re.search(r"[A-Za-z]{2}", k) and not k.startswith(("SS", "http")) and not re.fullmatch(r"[a-z_]+", k):
                used.add(k)

problems = 0
ph = re.compile(r"\{\w+\}")
for k, (hi, ur) in S.items():
    for lang, v in (("hi", hi), ("ur", ur)):
        if sorted(ph.findall(k)) != sorted(ph.findall(v)):
            print(f"placeholder mismatch [{lang}]: {k!r}")
            problems += 1
missing = sorted(k for k in used if k not in S and k.strip() not in ("Next", ""))
for k in missing:
    print(f"no translation: {k!r}")

lines = [
    "package app.sevasetu.patient.ui.i18n",
    "",
    "// Generated by app/i18n/build_strings.py from app/i18n/strings.py. Edit there, not here.",
    "// First-draft translations for the demo; a native speaker must review them (app/TRANSLATION_REVIEW.md).",
    "",
    "val STRINGS: Map<String, Map<String, String>> = mapOf(",
]
for k, (hi, ur) in S.items():
    lines.append(f"    {kotlin(k)} to mapOf(\"hi\" to {kotlin(hi)}, \"ur\" to {kotlin(ur)}),")
lines.append(")")
open(OUT, "w", encoding="utf8").write("\n".join(lines) + "\n")
print(f"wrote {len(S)} strings; {len(missing)} untranslated in code; {problems} placeholder problems")
sys.exit(1 if problems else 0)
